"""Generate compact runtime lookup tables from the original IANA snapshots.

This is a repository maintenance script, not a PNG command-line interface.
It does not access the network or alter the original registry files.
"""

from pathlib import Path
from pprint import pformat
from textwrap import wrap

ROOT = Path(__file__).parents[1]


def records(path: Path) -> list[dict[str, list[str]]]:
    result = []
    for block in path.read_text(encoding='utf-8').split('%%')[1:]:
        record: dict[str, list[str]] = {}
        key = None
        for line in block.splitlines():
            if line.startswith(' ') and key is not None:
                record[key][-1] += ' ' + line.strip()
            elif ': ' in line:
                key, value = line.split(': ', 1)
                record.setdefault(key, []).append(value)
        if record:
            result.append(record)
    return result


def _set(name: str, values: list[str]) -> str:
    lines = '\n'.join(
        f'        {line + " "!r}'
        for line in wrap(' '.join(sorted(values)), width=100, break_long_words=False, break_on_hyphens=False)
    )
    return f'{name} = frozenset(\n    (\n{lines}\n    ).split()\n)\n'


def generate() -> str:
    directory = ROOT.joinpath('assets', 'iana')
    subtags = records(directory.joinpath('language-subtag-registry.txt'))
    extensions = records(directory.joinpath('language-tag-extensions-registry.txt'))
    kinds = ('language', 'script', 'region', 'variant')
    values = {kind: [] for kind in kinds}
    ranges = {kind: [] for kind in kinds}
    prefixes = {}
    grandfathered = []
    for record in subtags:
        kind = record['Type'][0]
        if kind in kinds:
            value = record['Subtag'][0].lower()
            if '..' in value:
                ranges[kind].append(tuple(value.split('..')))
            else:
                values[kind].append(value)
        elif kind == 'extlang':
            (prefix,) = record['Prefix']
            prefixes[record['Subtag'][0].lower()] = prefix.lower()
        elif kind == 'grandfathered':
            grandfathered.append(record['Tag'][0].lower())
    header = '"""Generated by tools/generate_language_registry.py; do not edit manually.\n\n'
    for name in ('language-subtag-registry', 'language-tag-extensions-registry'):
        date = directory.joinpath(name + '.txt').read_text(encoding='utf-8').splitlines()[0]
        header += f'IANA {name}: {date}\n'
        header += f'https://www.iana.org/assignments/{name}/{name}\n'
    header += 'Original snapshots and provenance: assets/iana/.\n"""\n\n'
    for kind in kinds:
        header += _set(kind.upper() + '_SUBTAGS', values[kind]) + '\n'
    header += 'SUBTAGS = {\n' + ''.join(f'    {kind!r}: {kind.upper()}_SUBTAGS,\n' for kind in kinds) + '}\n\n'
    header += 'RANGES = ' + pformat({kind: tuple(value) for kind, value in ranges.items()}, sort_dicts=True) + '\n\n'
    header += 'EXTLANG_PREFIXES = ' + pformat(dict(sorted(prefixes.items())), sort_dicts=True) + '\n\n'
    header += _set('GRANDFATHERED', grandfathered) + '\n'
    return header + _set('EXTENSION_SINGLETONS', [record['Identifier'][0].lower() for record in extensions])


def main() -> None:
    ROOT.joinpath('src', 'png', '_language_data.py').write_text(generate(), encoding='utf-8')


if __name__ == '__main__':
    main()
