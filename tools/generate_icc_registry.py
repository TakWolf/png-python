"""Generate offline signature lookups from the selected official ICC registry.

Maintenance tool; no network access or PNG CLI. Ambiguous registry spellings
are retained separately instead of silently repairing the official data.
"""

import json
import re
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).parents[1]


def signatures(text: str) -> tuple[set[bytes], bool]:
    label, hexadecimal = text.rsplit('-', 1)
    candidates = set()
    if len(label) == 4 and label.isascii():
        candidates.add(label.encode('ascii'))
    if re.fullmatch(r'[0-9a-fA-F]{8}h?', hexadecimal):
        candidates.add(bytes.fromhex(hexadecimal.rstrip('h')))
    return candidates, len(candidates) != 1 or not re.fullmatch(r'[0-9a-fA-F]{8}h?', hexadecimal)


def generate() -> str:
    directory = ROOT.joinpath('assets', 'icc', 'registry')
    cmm, manufacturers, devices, uncertain = set(), set(), set(), set()
    for hexadecimal, label in json.loads(directory.joinpath('cmm.json').read_text()):
        values, ambiguous = signatures(label.strip("'\"") + '-' + hexadecimal)
        (uncertain if ambiguous else cmm).update(values)
    for text in json.loads(directory.joinpath('manufacturer.json').read_text()):
        values, ambiguous = signatures(text)
        (uncertain if ambiguous else manufacturers).update(values)
    uncertain_devices = set()
    for manufacturer, device in json.loads(directory.joinpath('device.json').read_text()):
        makers, maker_ambiguous = signatures(manufacturer)
        models, model_ambiguous = signatures(device)
        pairs = {(maker, model) for maker in makers for model in models}
        (uncertain_devices if maker_ambiguous or model_ambiguous else devices).update(pairs)
    result = '"""Generated by tools/generate_icc_registry.py; snapshot 2026-11-16."""\n\n'
    for name, values in [('CMM', cmm), ('MANUFACTURERS', manufacturers), ('DEVICES', devices),
                         ('UNCERTAIN', uncertain), ('UNCERTAIN_DEVICES', uncertain_devices)]:
        result += name + ' = frozenset(' + pformat(sorted(values), width=110) + ')\n\n'
    return result


def main() -> None:
    ROOT.joinpath('src', 'png', '_icc_registry_data.py').write_text(generate(), encoding='utf-8')


if __name__ == '__main__':
    main()
